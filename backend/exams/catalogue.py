def infer_metadata(name):
    upper = name.upper()
    if upper.startswith("SSC "): category = "SSC"
    elif "HIGH COURT" in upper or "COURT" in upper or "JUDICIAL" in upper: category = "COURT"
    elif upper.startswith(("RRB ", "RRB")): category = "RAILWAY"
    elif any(x in upper for x in ("POLICE", "HCM", "CAPF", "BSF", "SSB ", "CISF", "CRPF", "ITBP", "ARMY")): category = "POLICE"
    elif any(x in upper for x in ("UNIVERSITY", "UNIVERSITIES", "BHU ", "NTA ", "IIT ", "JNU ", "DU ")): category = "UNIVERSITY"
    elif any(x in upper for x in ("PSU", "NPCIL", "SPMCIL", "BELTRON", "BANK NOTE")): category = "PSU"
    elif "SPEED BOOSTER" in upper: category = "PRACTICE"
    elif any(x in upper for x in ("STATE", "BPSC", "DSSSB", "DDA ", "Bihar", "UP", "Rajasthan", "Jharkhand", "MPSC", "MP-", "RSSB", "RSMSSB", "WBPSC")): category = "STATE"
    elif any(x in upper for x in ("AIIMS", "CBSE", "NCERT", "NBEMS", "PGIMER", "JIPMER", "EMRS", "KVS", "DRDO", "EPFO", "POSTAL", "HARTRON", "CCRAS", "NIT ", "SILK BOARD", "LAHD", "IGNOU")): category = "CENTRAL"
    else: category = "OTHER"
    language = "HINDI" if any(x in upper for x in ("HINDI", "KURTIDEV", "KRUTIDEV", "MANGAL", "GAIL", "INSCRIPT")) else ("MARATHI" if "MARATHI" in upper else ("MIXED" if " & " in name else "ENGLISH"))
    script = next((s for s in ("KURTIDEV", "KRUTIDEV", "MANGAL", "REMINGTON GAIL", "INSCRIPT", "UNICODE") if s in upper), "")
    interface = "TCS" if "TCS" in upper else ("VH" if "VH CATEGORY" in upper else "")
    return category, language, script, interface
